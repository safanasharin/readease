function getCoords(pathStr) {
  const parts = pathStr.split(" ");
  let start = {x:0, y:0};
  let end = {x:0, y:0};
  
  // Find M x y
  const mIndex = parts.indexOf("M");
  if (mIndex !== -1) {
    start.x = parseInt(parts[mIndex+1]);
    start.y = parseInt(parts[mIndex+2]);
  }
  
  // Find last coordinate pair
  const nums = pathStr.match(/-?\d+/g);
  if (nums && nums.length >= 2) {
    end.x = parseInt(nums[nums.length-2]);
    end.y = parseInt(nums[nums.length-1]);
  }
  
  return {start, end};
}

